#!/usr/bin/env python3
"""Write docs/metrics.md, the metric glossary agents read, from target/semantic_manifest.json.

The glossary is generated so it cannot drift from the metric YAML. Each metric gets its
meaning, formula, source table, first complete date and the dimensions it can be grouped by
(spelled the way `mf query --group-by` expects).

    python scripts/build_glossary.py           # write docs/metrics.md (run dbt parse first)
    python scripts/build_glossary.py --check   # exit 1 if docs/metrics.md is out of date

Exit codes: 0 written or up to date, 1 stale (--check), 2 could not build.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parent.parent
MANIFEST = PROJECT_ROOT / "target" / "semantic_manifest.json"
GLOSSARY = PROJECT_ROOT / "docs" / "metrics.md"

HEADER = """# Metric glossary

Generated by `scripts/build_glossary.py` from the semantic manifest. Do not edit by hand; change the
metric YAML in `models/semantic/` and regenerate.

Query any metric with `mf query --metrics <name> --group-by <dimension> --start-time YYYY-MM-DD --end-time YYYY-MM-DD`.
Every metric can be grouped by `metric_time` (add `__week`, `__month`, ...). Dimensions are listed with
the prefix `mf` needs. Check **Data starts** before asking about an earlier period: an earlier window
returns a partial total, not an error.
"""


class GlossaryError(Exception):
    """The glossary could not be built."""


def _measure_models(manifest: dict) -> dict[str, dict]:
    return {m["name"]: sm for sm in manifest["semantic_models"] for m in sm.get("measures", [])}


def _primary_entity(model: dict) -> str | None:
    return next((e["name"] for e in model.get("entities", []) if e["type"] == "primary"), None)


def _has_video(model: dict) -> bool:
    return any(e["name"] == "video" for e in model.get("entities", []))


def _video_dimensions(manifest: dict) -> list[str]:
    videos = next((sm for sm in manifest["semantic_models"] if _primary_entity(sm) == "video"), None)
    if videos is None:
        return []
    return ["video"] + [f"video__{d['name']}" for d in videos.get("dimensions", [])]


def _model_dimensions(model: dict) -> list[str]:
    entity = _primary_entity(model)
    if entity is None:
        raise GlossaryError(f"semantic model {model['name']} has no primary entity, so its dimensions have no mf prefix")
    return [f"{entity}__{d['name']}" for d in model.get("dimensions", []) if d["type"] != "time"]


def _formula(metric: dict, by_measure: dict[str, dict]) -> str:
    params = metric["type_params"]
    if metric["type"] == "ratio":
        return f"{params['numerator']['name']} / {params['denominator']['name']}"
    if metric["type"] == "derived":
        return params["expr"]
    if not params.get("measure"):
        return metric["type"]
    name = params["measure"]["name"]
    measure = next((m for m in by_measure[name].get("measures", []) if m["name"] == name), {})
    if measure.get("non_additive_dimension"):
        return f"measure `{name}` at the latest snapshot in each period, summed across videos"
    return f"sum of measure `{name}`"


def _metric(manifest: dict, name: str) -> dict:
    found = next((m for m in manifest["metrics"] if m["name"] == name), None)
    if found is None:
        raise GlossaryError(f"metric {name} not found")
    return found


def metric_section(manifest: dict, name: str) -> str:
    metric = _metric(manifest, name)
    meta = (metric.get("config") or {}).get("meta") or {}
    if not meta.get("coverage_start"):
        raise GlossaryError(f"metric {name} has no config.meta.coverage_start")

    by_measure = _measure_models(manifest)
    models = {by_measure[m["name"]]["name"]: by_measure[m["name"]] for m in metric["type_params"]["input_measures"]}
    dims = ["metric_time"]
    if len(models) == 1:
        dims += _model_dimensions(next(iter(models.values())))
    if all(_has_video(m) for m in models.values()):
        dims += _video_dimensions(manifest)

    return "\n".join([
        f"### `{name}`: {metric.get('label') or name}",
        "",
        metric["description"],
        "",
        f"- **Type:** {metric['type']} ({_formula(metric, by_measure)})",
        f"- **Source:** `{meta.get('source', 'unknown')}`",
        f"- **Data starts:** {meta['coverage_start']}",
        f"- **Group by:** {', '.join(f'`{d}`' for d in dims)}",
        "",
    ])


def build_glossary(manifest: dict) -> str:
    by_measure = _measure_models(manifest)
    groups: dict[str, list[str]] = {}
    for metric in sorted(manifest["metrics"], key=lambda m: m["name"]):
        first = metric["type_params"]["input_measures"][0]["name"]
        groups.setdefault(by_measure[first]["name"], []).append(metric["name"])

    parts = [HEADER]
    for model_name in sorted(groups):
        model = next(sm for sm in manifest["semantic_models"] if sm["name"] == model_name)
        parts.append(f"## {model_name}\n\n{model.get('description', '')}\n")
        parts += [metric_section(manifest, name) for name in groups[model_name]]
    return "\n".join(parts).rstrip() + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Write the metric glossary from the semantic manifest.")
    parser.add_argument("--manifest", type=Path, default=MANIFEST)
    parser.add_argument("--out", type=Path, default=GLOSSARY)
    parser.add_argument("--check", action="store_true", help="exit 1 if the glossary is out of date")
    args = parser.parse_args(argv)

    try:
        manifest = json.loads(args.manifest.read_text())
        text = build_glossary(manifest)
    except (OSError, json.JSONDecodeError, KeyError, GlossaryError) as err:
        print(f"GLOSSARY ERROR: {err}. Run dbt parse first.", file=sys.stderr)
        return 2

    if args.check:
        current = args.out.read_text() if args.out.exists() else ""
        if current != text:
            print(f"{args.out} is out of date. Run python scripts/build_glossary.py.", file=sys.stderr)
            return 1
        print(f"{args.out} is up to date.")
        return 0

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(text)
    print(f"Wrote {args.out} ({len(manifest['metrics'])} metrics).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
